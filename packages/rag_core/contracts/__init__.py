"""Stage C - core contracts (`core/modules_spec.md`).

This subpackage publishes the pure, transport-agnostic contracts of the Enterprise RAG core:

- `enums`      - the canonical enumerations (access levels, intents, license plans/features, ...);
- `models`     - the Pydantic V2 domain models (licensing, tenants, documents, chunks, search,
                 generation, access control, admin panel, vendor backoffice, observability);
- `settings`   - the `Settings` object (pydantic-settings), the single source of runtime config;
- `interfaces` - the abstract `Base*` ports (licensing, policy, storage, embedder, retriever,
                 reranker, LLM, channels, tracing) wired to providers via the DI container.

Everything here is free of any dependency on the transport layer (`services/api`) or the DB
driver; implementations (providers) are bound to the ports in later stages via `rag_core.di`.
"""

